#!/usr/bin/env python3
"""DEV-34 Linux/root native rehearsal with owned synthetic targets only.

The local forced-command transport executes the real coordinator/target and
producer dispatch code; it is not an SSH trust/connection test. Source payload
must be the synthetic retained fixture generated by test_isolated_restore_native.
No installed production paths, keys, DNS connections or published ports are used.
"""
from __future__ import annotations

import argparse
import io
import json
import os
from pathlib import Path
import re
